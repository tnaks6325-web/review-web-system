// 사용자 확정: "결과물 = 포스팅URL만 제출 = 리뷰제출 완료".
// 그래서 blog 탭에서는 이 값이 **완료 조건**이고, 서버가 최종 방어다(화면만 막으면 우회된다).
//
// ★★ 형식만 본다 — 도메인 화이트리스트 금지.
//   리뷰어가 어느 블로그 플랫폼에 쓸지는 우리가 정하지 않는다(네이버·티스토리·브런치·
//   자체 도메인…). 목록을 두는 순간 **정상 제출이 막히는 쪽**이 되고, 그건 이 레포가
//   1차 필터에서 이미 정한 실패 선호(오탐 > 미탐 금지)와 정반대다.
// ★ 통과 기준 = `http`/`https` 절대 URL + 호스트에 점 1개 이상. 그 이상 좁히지 않는다.
// ★ 공백·따옴표·꺾쇠는 거부(시트 칸·화면에 그대로 나가는 값이라 속성 breakout 여지를 없앤다).
// ═══════════════════════════════════════════════════════════════════════════

/** 사람에게 보여줄 안내문 — 서버 거부 메시지와 화면 힌트가 갈리지 않게 한 곳에 둔다. */
const POST_URL_HINT = '포스팅URL을 입력해주세요 (http:// 또는 https:// 로 시작하는 주소)';

/**
 * 블로그URL(= 그 사람의 **블로그 주소**) 안내문.
 * ★ 형식 규칙은 포스팅URL과 **같은 `isPostUrl` 하나**를 쓴다(둘 다 사람이 붙여넣는 주소).
 *   가리키는 대상만 다르다 — 블로그URL = 블로그 주소(모집·선정 시점) / 포스팅URL = 쓴 글 주소(작업 완료 시점).
 *   규칙을 둘로 나누면 "블로그 주소는 되는데 포스팅 주소는 거부"처럼 조용히 갈라진다.
 */
const BLOG_URL_HINT = 'http:// 또는 https:// 로 시작하는 블로그 주소';

/**
 * @param {*} v 입력값(사람이 붙여넣은 문자열)
 * @returns {boolean} 포스팅URL 로 인정할 수 있는가
 */
function isPostUrl(v) {
  const s = String(v == null ? '' : v).trim();
  if (!s) return false;
  if (/[\s"'<>]/.test(s)) return false;          // 공백·따옴표·꺾쇠 = 주소 하나가 아니다
  if (!/^https?:\/\//i.test(s)) return false;
  const host = s.replace(/^https?:\/\//i, '').split(/[/?#]/)[0];
  return host.includes('.') && host.length > 3;  // 호스트가 최소한 `a.bc` 꼴은 되어야 한다
}

/** 저장·전송 직전 정규화 — 앞뒤 공백만 턴다(주소 자체는 손대지 않는다). */
function normalizePostUrl(v) {
  return String(v == null ? '' : v).trim();
}

module.exports = { isPostUrl, normalizePostUrl, POST_URL_HINT, BLOG_URL_HINT };
