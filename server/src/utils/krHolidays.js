'use strict';

/**
 * 대한민국 법정공휴일 — 서버 판정의 단일 출처.
 *
 * ★★ 이 목록은 **신청 막기·다음 오픈일·이월·작업표 날짜 분배**가 함께 본다.
 *   조절 화면(frontend/js/campaign-daily-plan.js)의 같은 표는 이 파일의 사본이며,
 *   회귀가드(tests/campaignHolidayClosure.test.js)가 두 표의 글자 그대로 일치를 고정한다.
 *   한쪽만 고치면 "화면은 휴무인데 서버는 연다"(2026-09-23 추석 사고)가 재현된다.
 *
 * ★ 양력 고정일은 계산으로, 음력·대체공휴일은 연도별 확정값 표로 둔다 — 음력은 계산식으로
 *   만들 수 없고 대체공휴일은 해마다 정부가 확정한다. 추측으로 채우지 않는다(틀린 값 > 빈 값).
 * ★ 표에 없는 연도는 **고정일만** 공휴일로 본다 — 그 해 음력 공휴일은 평일로 열린다.
 *   `isLunarYearKnown` 이 false 면 호출부가 경고를 남긴다(조용히 열리지 않게).
 */

const FIXED_HOLIDAYS = {                     // MM-DD → 이름 (매년 같은 날)
  '01-01': '신정', '03-01': '삼일절', '05-05': '어린이날', '06-06': '현충일',
  '08-15': '광복절', '10-03': '개천절', '10-09': '한글날', '12-25': '성탄절',
};

const LUNAR_HOLIDAYS = {                     // 음력 기반 + 대체공휴일(연도별 확정값)
  '2026-02-16': '설날 연휴', '2026-02-17': '설날', '2026-02-18': '설날 연휴',
  '2026-03-02': '삼일절 대체', '2026-05-24': '부처님오신날', '2026-05-25': '부처님오신날 대체',
  '2026-09-24': '추석 연휴', '2026-09-25': '추석', '2026-09-26': '추석 연휴',
  '2027-02-05': '설날 연휴', '2027-02-06': '설날', '2027-02-07': '설날 연휴', '2027-02-08': '설날 대체',
  '2027-05-13': '부처님오신날', '2027-06-07': '현충일 대체', '2027-08-16': '광복절 대체',
  '2027-09-14': '추석 연휴', '2027-09-15': '추석', '2027-09-16': '추석 연휴',
  '2027-10-04': '개천절 대체', '2027-10-11': '한글날 대체', '2027-12-27': '성탄절 대체',
};

const ISO_RE = /^(\d{4})-(\d{2})-(\d{2})$/;

/** 그날의 공휴일 이름 — 없으면 '' (형식 밖 값도 '') */
function holidayName(iso) {
  const s = String(iso || '').trim();
  if (!ISO_RE.test(s)) return '';
  return LUNAR_HOLIDAYS[s] || FIXED_HOLIDAYS[s.slice(5)] || '';
}

function isHoliday(iso) { return holidayName(iso) !== ''; }

/** 그 해의 음력·대체공휴일 표가 있는가 */
function isLunarYearKnown(iso) {
  const y = String(iso || '').slice(0, 4);
  return Object.keys(LUNAR_HOLIDAYS).some(k => k.slice(0, 4) === y);
}

module.exports = { FIXED_HOLIDAYS, LUNAR_HOLIDAYS, holidayName, isHoliday, isLunarYearKnown };
