-- ═══════════════════════════════════════════════════════════
-- 066: 일 모집한도 미달분 자동 이월 — 소급 기준선(anchor)
--
-- 배경: 일건수 20인데 15명만 모이면, 관리자가 다음날 공고수정으로 일건수를 25로 올리고
--   25가 채워지면 다시 20으로 되돌리는 일을 손으로 하고 있었다. 이 계산을 시스템이 한다.
--
--   그날 정원 = min(daily_limit × 경과일수, 상한) − 기준선 이후 누적확정
--   → 어제 5명 부족하면 오늘 25, 오늘 25가 다 차면 내일 다시 20.
--   (시트 일정이 인식되는 캠페인은 063이 이미 같은 방식으로 이월하고 있다 — 이 설정은
--    시트 일정이 없는 캠페인의 daily_limit 경로에만 쓰인다.)
--
-- ★ 이 키가 "언제부터 세기 시작할지"를 고정한다.
--   없으면 이미 몇 주째 진행 중인 캠페인의 과거 미달분이 배포 당일 한꺼번에 열려
--   하루에 수십 건이 쏟아진다. 062의 캡처 감지 컷오프와 같은 소급 차단 장치다.
--   ON CONFLICT DO NOTHING = 재배포해도 기준선이 앞당겨지지 않는다(멱등).
--
-- 되돌리기: env CAMPAIGN_DAILY_CARRY=0 (즉시 종전 동작). 이 행은 지워도 무해.
-- ═══════════════════════════════════════════════════════════
INSERT INTO app_settings (key, value, updated_at)
VALUES ('campaign_carry_start', to_char((NOW() AT TIME ZONE 'Asia/Seoul')::date, 'YYYY-MM-DD'), NOW())
ON CONFLICT (key) DO NOTHING;
