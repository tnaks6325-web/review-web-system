-- ═══════════════════════════════════════════════════════════
-- 126: 구매시간만료 자동 취소확정 — 사람/시스템 확정 구분 마커
-- ───────────────────────────────────────────────────────────
-- 만료(구매시간만료) 중 **연결된 주문이 하나도 없는 건**(= 신청만 하고 구매하지 않음)은
-- 매분 스윕이 자동으로 취소확정(dismissed_at)한다. 그러면 관제에서 사람이 매번
-- [취소확정]을 누르지 않아도 목록·지각 배지가 정리된다.
--
-- ★ dismissed_by 가 필요한 이유 = **되살리기 판정**.
--   만료 직후 도착한 주문(late_order_id)이 자동 취소확정된 뒤에 붙는 경우가 있는데,
--   그때 그 줄을 되살려야 결제한 리뷰어가 조용히 누락되지 않는다.
--   되살리는 대상은 **시스템이 확정한 건('auto')뿐** — 사람이 "미참여"로 판단한 건은
--   시스템이 되돌리지 않는다(사람 결정 우선). 기존 행은 NULL = 사람 = 되살림 대상 아님.
--
-- ★ nullable·additive — 기존 행/동작 무영향. 078(dismissed_at)과 같은 계열 마커라
--   quota/유효홀드(status='applied' AND expires_at>now)에는 일절 영향 없음.
-- ═══════════════════════════════════════════════════════════

ALTER TABLE campaign_applications ADD COLUMN IF NOT EXISTS dismissed_by TEXT;
