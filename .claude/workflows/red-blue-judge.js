const TASK = args && args.task ? args.task : '(no task provided — args.task 에 과제를 넘기세요)'

const REPO_CTX = `저장소: review-web-system (Node.js Express + PostgreSQL + 구글시트 미러, Railway, 다중 인스턴스 가능, Sheets 쿼터 45/분 throttle). 실제 코드를 Read/Grep으로 읽고 사실확인하라. 추측 금지.`

phase('Red')
const red = await agent(
`너는 레드팀(적대적 오류 예측자)다. ${REPO_CTX}

## 과제
${TASK}

## 임무
이 변경이 라이브에 배포됐을 때 "터질 수 있는" 모든 오류 상황을 적대적으로 예측해 제시하라. 동시성/경쟁상태, 엣지케이스·경계값(그리드밖 행, 캐시 stale, 헤더미검출, 탭리네임/gid null, 손상데이터), 쿼터·처리량, 권한·보안, 되돌리기-어려움·데이터정합성(손실/중복/멱등깨짐), 장애전파·폴백 소실 관점을 커버하라.
각 시나리오: **시나리오(한줄) / 재현경로(file:line 인용) / 결과(손실·중복·쿼터·무한루프 등) / 심각도(🔴치명·🟡중간·🔵경미)**. 5~12개 고신호 항목으로 심각도순 정렬. 코드는 고치지 말고 위험만 보고.`,
  { label: 'red-team', phase: 'Red' }
)

phase('Blue')
const blue = await agent(
`너는 블루팀(방어 설계자)다. ${REPO_CTX}

## 과제
${TASK}

## 레드팀이 예측한 오류 시나리오
${red}

## 임무
위 레드 시나리오를 막는 **코드구조를 설계**하라. 모든 🔴/🟡 항목에 1:1 대응(각 방어가 어느 레드 시나리오를 닫는지 명시). 기존 패턴 재사용 우선(파라미터 바인딩 \`$1\`, \`throttledCall\`, \`sheet_row_claims\` 2중 유니크 멱등, \`_batchWriteByGrid\`의 \`appendDimension\`). 손실 0·멱등·쿼터안전·되돌릴수있음 기본.
산출: ① 방어 설계 개요, ② 레드 대응표(시나리오→방어→적용위치 file:line), ③ **적용 가능한 구체 코드**(실제 함수명·시그니처에 맞춘 스니펫/교체블록), ④ 검증방법(단위테스트/수동확인), ⑤ 남은 트레이드오프. 실제 코드를 읽고 시그니처를 확인한 뒤 설계하라.`,
  { label: 'blue-team', phase: 'Blue' }
)

phase('Judge')
const judge = await agent(
`너는 심판(검증·확정자)다. 라이브 적용 직전 마지막 게이트다. ${REPO_CTX}

## 과제
${TASK}

## 레드팀 오류 시나리오
${red}

## 블루팀 방어 설계
${blue}

## 임무
레드↔블루를 대조 검증하라. 코드를 직접 읽어 블루의 스니펫이 실제 시그니처·반환형과 맞는지, 정말 그 위험을 닫는지 확인하라(블루·레드를 맹신 금지).
산출:
1. **판정 요약**: 채택/수정/기각한 방어와 이유.
2. **레드↔블루 대조표**: 시나리오 | 블루 방어 | 판정(✅막음/⚠️부분/❌누락/🔵과잉) | 심판 조치.
3. **빈틈**: 블루가 놓친 레드 항목, 블루가 새로 만든 위험(멱등·쿼터 깨짐 등), 양팀이 함께 놓친 위험.
4. **최종 코드(파일별)**: 위 검증을 반영한 **적용 가능한 디프/교체블록**. 메인루프가 그대로 적용할 만큼 구체적으로(실제 함수명·시그니처 정확히). 손실0·멱등·쿼터안전·되돌릴수있음 만족.
5. **검증계획 + 잔여위험**: 적용 후 확인 절차(단위테스트 추가/수정, node --check, 수동확인)와 남는 위험(없으면 근거와 함께 "없음").`,
  { label: 'judge', phase: 'Judge' }
)

return { red, blue, judge }
